-- W5 ランキング（docs/protocol.md）
-- 届いた 12bit の断片を、送り元（IP・経路）ごとに組み立て中のフレーム
CREATE TABLE IF NOT EXISTS frames (
  ip TEXT NOT NULL, ch INTEGER NOT NULL, kind INTEGER NOT NULL, need INTEGER NOT NULL, words TEXT NOT NULL, ts INTEGER NOT NULL,
  PRIMARY KEY (ip, ch)
);
-- 試合の報告の半分（A：文字列の経路＝試合番号と結果、B：画像の経路＝プレイヤーの ID）。同じ IP から近い時刻に届いた A と B を順に組む
CREATE TABLE IF NOT EXISTS halves (
  id INTEGER PRIMARY KEY AUTOINCREMENT, ip TEXT NOT NULL, part TEXT NOT NULL, a INTEGER NOT NULL, b INTEGER NOT NULL, ts INTEGER NOT NULL, used INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS halves_ip ON halves (ip, part, used, ts);
-- 試合の報告（1 人分）。同じ試合・同じ人は 1 つ（最初のものを採る）
CREATE TABLE IF NOT EXISTS reports (
  match_id INTEGER NOT NULL, rid INTEGER NOT NULL, result INTEGER NOT NULL, kind INTEGER NOT NULL, ranked INTEGER NOT NULL,
  ip TEXT NOT NULL, ts INTEGER NOT NULL, PRIMARY KEY (match_id, rid)
);
CREATE INDEX IF NOT EXISTS reports_ts ON reports (ts);
-- 集計済みの試合（二重に数えない）
CREATE TABLE IF NOT EXISTS counted (match_id INTEGER NOT NULL, rid INTEGER NOT NULL, ts INTEGER NOT NULL, PRIMARY KEY (match_id, rid));
CREATE TABLE IF NOT EXISTS rated (match_id INTEGER PRIMARY KEY, a INTEGER NOT NULL, b INTEGER NOT NULL, ts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS players (rid INTEGER PRIMARY KEY, name TEXT NOT NULL DEFAULT '', ts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS stats (rid INTEGER NOT NULL, kind INTEGER NOT NULL, matches INTEGER NOT NULL DEFAULT 0, wins INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (rid, kind));
CREATE TABLE IF NOT EXISTS ratings (rid INTEGER NOT NULL, family INTEGER NOT NULL, rating REAL NOT NULL, games INTEGER NOT NULL, PRIMARY KEY (rid, family));
-- 報告の送り元（試合ごとの IP。2 か所から届いたかを見る）
CREATE TABLE IF NOT EXISTS sources (match_id INTEGER NOT NULL, ip TEXT NOT NULL, ts INTEGER NOT NULL, PRIMARY KEY (match_id, ip));
